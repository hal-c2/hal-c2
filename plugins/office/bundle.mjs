// Writes ui/OfficePage.qml, the one file clients fetch, from src/: the page,
// with every other file there and in the engine (the ljos-play submodule,
// https://github.com/hal-c2/ljos-play) as an inline component of it. `--check`
// fails when the written file is stale. The submodule is checked out first if
// it is not yet; to move the engine, check out another commit in it.
//
//   node plugins/office/bundle.mjs [--check]
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL(".", import.meta.url));
const source = join(root, "src");
const checkout = join(root, "ljos-play");
const engine = join(checkout, "qml", "LjosPlay");
const target = join(root, "ui", "OfficePage.qml");
const page = join(source, "OfficePage.qml");
const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");
const git = (cwd, ...args) => execFileSync("git", ["-C", cwd, ...args], { encoding: "utf8" });

// A QML document as its imports, the comment over its root, and its root.
function parse(path, text = read(path)) {
  const lines = text.replace(/\r\n/g, "\n").trimEnd().split("\n");
  const start = lines.findIndex((line) => /^[A-Z][\w.]*\s*\{$/.test(line));
  if (start < 0 || lines.at(-1) !== "}")
    throw new Error(`${path}: expected one root object, its braces in the first column`);
  const head = lines.slice(0, start);
  return {
    name: basename(path, ".qml"),
    type: lines[start].slice(0, -1).trim(),
    imports: head.filter((line) => line.startsWith("import ") && !line.startsWith('import "')),
    comment: head.filter((line) => line.startsWith("//")),
    body: lines.slice(start + 1, -1),
  };
}

if (!existsSync(engine)) git(root, "submodule", "update", "--init", "--", "ljos-play");
// The bundle names the engine's commit and is read from it, so files git
// ignores or does not track never ship; changes not yet committed are refused
// rather than left out without a word.
if (git(checkout, "status", "--porcelain", "--", "qml", "LICENSE").trim())
  throw new Error(`${checkout} has changes to the engine: commit them first`);
const commit = git(checkout, "rev-parse", "HEAD").trim();
const atCommit = (path) => git(checkout, "show", `${commit}:${path}`);
const engineParts = git(checkout, "ls-tree", "--name-only", commit, "qml/LjosPlay/")
  .split("\n")
  .filter((path) => path.endsWith(".qml"))
  .sort()
  .map((path) => parse(path, atCommit(path)));

const qmlIn = (directory) =>
  readdirSync(directory)
    .filter((file) => file.endsWith(".qml"))
    .sort()
    .map((file) => join(directory, file));

const main = parse(page);
const parts = [...qmlIn(source).filter((path) => path !== page).map((path) => parse(path)), ...engineParts];
const names = new Set();
for (const part of parts) {
  if (names.has(part.name)) throw new Error(`Two files are called ${part.name}`);
  names.add(part.name);
}

const indent = (line) => (line ? `    ${line}` : line);
const output = [
  "// Generated by plugins/office/bundle.mjs from plugins/office/src. Don't edit this file.",
  "//",
  `// It carries LjosPlay ${commit} (https://github.com/hal-c2/ljos-play),`,
  "// under this license:",
  "//",
  ...atCommit("LICENSE")
    .trimEnd()
    .split("\n")
    .map((line) => `// ${line}`.trimEnd()),
  "",
  "pragma ComponentBehavior: Bound",
  ...new Set([main, ...parts].flatMap((document) => document.imports)),
  "",
  ...main.comment,
  `${main.type} {`,
  ...main.body,
  ...parts.flatMap((part) => [
    "",
    ...part.comment.map(indent),
    `    component ${part.name}: ${part.type} {`,
    ...part.body.map(indent),
    "    }",
  ]),
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (read(target) !== output) {
    console.error("ui/OfficePage.qml is stale: run node plugins/office/bundle.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
