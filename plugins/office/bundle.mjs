// Writes ui/OfficePage.qml, the one file clients fetch, from src/: the page,
// with every other file there and in the pinned engine (src/LjosPlay) as an
// inline component of it. `--check` fails when the written file is stale.
// `--engine <ljos-play checkout>` first pins the engine at that checkout's
// commit (https://github.com/hal-c2/ljos-play), which must have no changes.
//
//   node plugins/office/bundle.mjs [--check | --engine <checkout>]
import { execFileSync } from "node:child_process";
import { cpSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL(".", import.meta.url));
const source = join(root, "src");
const engine = join(source, "LjosPlay");
const target = join(root, "ui", "OfficePage.qml");
const page = join(source, "OfficePage.qml");
const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

// A QML document as its imports, the comment over its root, and its root.
function parse(path) {
  const lines = read(path).trimEnd().split("\n");
  const start = lines.findIndex((line) => /^[A-Z][\w.]*\s*\{$/.test(line));
  if (start < 0 || lines.at(-1) !== "}")
    throw new Error(`${path}: expected one root object, its braces in the first column`);
  const head = lines.slice(0, start);
  return {
    name: basename(path, ".qml"),
    type: lines[start].slice(0, -1).trim(),
    imports: head.filter((line) => line.startsWith("import ") && !line.startsWith('import "')),
    comment: head.filter((line) => line.startsWith("//")),
    body: lines.slice(start + 1, -1),
  };
}

// Replaces src/LjosPlay with the engine of a ljos-play checkout, its license
// and the commit it is at.
function pin(checkout) {
  const git = (...args) => execFileSync("git", ["-C", checkout, ...args], { encoding: "utf8" });
  if (git("status", "--porcelain", "--", "qml", "LICENSE").trim())
    throw new Error(`${checkout} has changes to the engine: commit them first`);
  rmSync(engine, { recursive: true, force: true });
  cpSync(join(checkout, "qml", "LjosPlay"), engine, { recursive: true });
  cpSync(join(checkout, "LICENSE"), join(engine, "LICENSE"));
  writeFileSync(join(engine, "COMMIT"), git("rev-parse", "HEAD"));
}

const engineAt = process.argv.indexOf("--engine");
if (engineAt >= 0) {
  if (!process.argv[engineAt + 1]) throw new Error("--engine needs a ljos-play checkout");
  pin(resolve(process.argv[engineAt + 1]));
}

const qmlIn = (directory) =>
  readdirSync(directory)
    .filter((file) => file.endsWith(".qml"))
    .sort()
    .map((file) => join(directory, file));

const main = parse(page);
const parts = [...qmlIn(source).filter((path) => path !== page), ...qmlIn(engine)].map(parse);
const names = new Set();
for (const part of parts) {
  if (names.has(part.name)) throw new Error(`Two files are called ${part.name}`);
  names.add(part.name);
}

const indent = (line) => (line ? `    ${line}` : line);
const output = [
  "// Generated by plugins/office/bundle.mjs from plugins/office/src. Don't edit this file.",
  "//",
  `// It carries LjosPlay ${read(join(engine, "COMMIT")).trim()} (https://github.com/hal-c2/ljos-play),`,
  "// under this license:",
  "//",
  ...read(join(engine, "LICENSE"))
    .trimEnd()
    .split("\n")
    .map((line) => `// ${line}`.trimEnd()),
  "",
  "pragma ComponentBehavior: Bound",
  ...new Set([main, ...parts].flatMap((document) => document.imports)),
  "",
  ...main.comment,
  `${main.type} {`,
  ...main.body,
  ...parts.flatMap((part) => [
    "",
    ...part.comment.map(indent),
    `    component ${part.name}: ${part.type} {`,
    ...part.body.map(indent),
    "    }",
  ]),
  "}",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (read(target) !== output) {
    console.error("ui/OfficePage.qml is stale: run node plugins/office/bundle.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
